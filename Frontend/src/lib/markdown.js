/**
 * src/lib/markdown.js
 * یوتیلیتی تخصصی نرمال‌سازی متون مارک‌داون
 * برای جلوگیری از باگ‌های ناشی از حذف شدن اینترها (\n) در Prisma Studio یا اینپوت‌های ادمین
 */

/**
 * نرمال‌سازی دفاعی متون مارک‌داون قبل از ارسال به موتور رندر CommonMark
 * @param {string} content - متن ورودی خام مارک‌داون
 * @returns {string} - متن نرمال‌شده با فاصله‌گذاری و اینترهای استاندارد
 */
export function normalizeMarkdown(content) {
  if (!content || typeof content !== "string") return "";

  // ۱. تبدیل تمام شکستگی‌های خط ویندوز (\r\n یا \r) به یونیکس (\n)
  let text = content.replace(/\r\n/g, "\n").replace(/\r/g, "\n");

  // ۲. افزودن دو خط جدید (\n\n) قبل از هدینگ‌ها (# تا ######) در صورتی که به متن قبلی چسبیده باشند
  text = text.replace(/([^\n#])([ \t]*)(#{1,6}[ \t]+)/g, "$1\n\n$3");
  // در صورتی که قبل از هدینگ فقط یک خط جدید باشد، به دو خط جدید تبدیل می‌شود
  text = text.replace(/([^\n])\n(#{1,6}[ \t]+)/g, "$1\n\n$2");

  // ۳. افزودن خط جدید قبل از آیتم‌های لیست ستاره‌ای (*) بدون آسیب به تگ‌های ضخیم (**متن**)
  text = text.replace(/([^\n*])([ \t]*)(\*(?!\*)[ \t]+)/g, "$1\n$3");

  // ۴. افزودن خط جدید قبل از آیتم‌های لیست خط تیره‌ای (-) بدون آسیب به خط جداکننده (---)
  text = text.replace(/([^\n\-])([ \t]*)(-(?!-)[ \t]+)/g, "$1\n$3");

  // ۵. افزودن خط جدید قبل از لیست‌های شماره‌دار (مانند 1. یا 2.)
  text = text.replace(/([^\n])([ \t]*)(\d+\.[ \t]+)/g, "$1\n$3");

  // ۶. افزودن خط جدید مضاعف قبل از نقل‌قول‌ها (> Blockquote)
  text = text.replace(/([^\n>])([ \t]*)(>[ \t]*)/g, "$1\n\n$3");

  // ۷. یکپارچه‌سازی خطوط خالی متوالی بیش از ۲ اینتر
  text = text.replace(/\n{3,}/g, "\n\n");

  return text.trim();
}
